-- ---------------------------------------------------------------------
-- 範例 1：列出資料庫裡有哪些資料表
-- sqlite_master 是 SQLite 內建的「系統資料表」，記錄資料庫的結構
-- （其他資料庫的寫法不同，例如 SQL Server 用 INFORMATION_SCHEMA.TABLES）
-- ---------------------------------------------------------------------
SELECT name FROM sqlite_master WHERE type = 'table';


-- ---------------------------------------------------------------------
-- 範例 2：查看 exams 資料表的「綱要（Schema）」
-- 會列出每一欄的名稱（name）、型態（type）、是否不可為空（notnull）、是否為主鍵（pk）
-- ---------------------------------------------------------------------
PRAGMA table_info(exams);


-- ---------------------------------------------------------------------
-- 範例 3：查看 exams 資料表的「實例（Instance）」，也就是目前的資料
-- ---------------------------------------------------------------------
SELECT * FROM exams;


-- ---------------------------------------------------------------------
-- 範例 4：計算 exams 的 Cardinality（列數）
-- ---------------------------------------------------------------------
SELECT COUNT(*) FROM exams;


-- ---------------------------------------------------------------------
-- 範例 5：用 typeof() 看每個值實際的資料型態
-- 注意第 29 題的 answer 是 null
-- ---------------------------------------------------------------------
SELECT question_id, score, typeof(score), answer, typeof(answer)
FROM questions
WHERE question_id IN (1, 7, 29);


-- ---------------------------------------------------------------------
-- 範例 6：NULL、0、空字串不一樣
-- ---------------------------------------------------------------------
SELECT typeof(NULL), typeof(0), typeof('');


