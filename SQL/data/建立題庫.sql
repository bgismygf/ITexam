PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS practice_log;
DROP TABLE IF EXISTS question_topics;
DROP TABLE IF EXISTS options;
DROP TABLE IF EXISTS questions;
DROP TABLE IF EXISTS topics;
DROP TABLE IF EXISTS exams;

-- 考試（每一份試卷一筆）
CREATE TABLE exams (
    exam_id        INTEGER PRIMARY KEY,      -- 考試編號
    year           INTEGER NOT NULL,         -- 民國年
    organizer      TEXT    NOT NULL,         -- 招考單位
    category       TEXT    NOT NULL,         -- 類別（例如：資訊）
    subject        TEXT    NOT NULL,         -- 科目
    question_count INTEGER,                  -- 題數
    wrong_penalty  INTEGER NOT NULL DEFAULT 0 -- 答錯是否倒扣：1=是，0=否
);

-- 題目
CREATE TABLE questions (
    question_id INTEGER PRIMARY KEY,         -- 題目編號（整個題庫唯一）
    exam_id     INTEGER NOT NULL REFERENCES exams(exam_id),
    question_no INTEGER NOT NULL,            -- 在該試卷中的題號
    content     TEXT    NOT NULL,            -- 題目內容
    score       REAL    NOT NULL,            -- 配分
    answer      TEXT,                        -- 正確答案（A/B/C/D），NULL = 尚未輸入
    UNIQUE (exam_id, question_no)
);

-- 選項
CREATE TABLE options (
    question_id INTEGER NOT NULL REFERENCES questions(question_id),
    label       TEXT    NOT NULL,            -- A/B/C/D
    content     TEXT    NOT NULL,            -- 選項內容
    PRIMARY KEY (question_id, label)
);

-- 章節主題
CREATE TABLE topics (
    topic_id INTEGER PRIMARY KEY,
    name     TEXT NOT NULL UNIQUE
);

-- 題目與章節的對應（一題可以屬於多個章節）
CREATE TABLE question_topics (
    question_id INTEGER NOT NULL REFERENCES questions(question_id),
    topic_id    INTEGER NOT NULL REFERENCES topics(topic_id),
    PRIMARY KEY (question_id, topic_id)
);

-- 作答紀錄
CREATE TABLE practice_log (
    log_id      INTEGER PRIMARY KEY,
    question_id INTEGER NOT NULL REFERENCES questions(question_id),
    answered_at TEXT    NOT NULL,            -- 作答時間
    chosen      TEXT    NOT NULL,            -- 選了哪個選項
    is_correct  INTEGER NOT NULL             -- 1=答對，0=答錯
);

